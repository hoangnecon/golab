package main

import (
	"context"
	"encoding/json"
	"fmt"
	"log"
	"os"
	"time"

	"github.com/hoangnecon/golab/internal/bridge"
	"github.com/hoangnecon/golab/internal/service/kernel"
	"github.com/hoangnecon/golab/internal/service/notebook"
	"github.com/hoangnecon/golab/internal/service/proxy"
	"github.com/hoangnecon/golab/internal/service/storage"
	"github.com/hoangnecon/golab/internal/service/telemetry"
	"github.com/hoangnecon/golab/internal/service/terminal"
)

func main() {
	cdpURL := os.Getenv("COLAB_CDP_URL")
	if cdpURL == "" {
		cdpURL = "http://127.0.0.1:9222"
	}

	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()

	fmt.Printf("\n=== GOLAB ENTERPRISE HARNESS VERIFICATION SUITE ===\n")
	fmt.Printf("Connecting to CDP at %s...\n", cdpURL)

	cdp := bridge.NewCDPClient(cdpURL)
	if err := cdp.Connect(ctx); err != nil {
		log.Fatalf("CDP Connect failed: %v", err)
	}
	defer cdp.Close()

	exec := bridge.NewColabExecutor(cdp)
	storageSvc := storage.NewService(exec)
	kernelSvc := kernel.NewService(exec)
	telemetrySvc := telemetry.NewService(exec)
	terminalSvc := terminal.NewService(exec)
	notebookSvc := notebook.NewService(exec)
	proxySvc := proxy.NewService(exec)

	passed := 0
	total := 0

	runTest := func(name string, fn func() error) {
		total++
		start := time.Now()
		err := fn()
		elapsed := time.Since(start).Milliseconds()
		if err != nil {
			fmt.Printf("❌ [%s] FAILED (%dms): %v\n", name, elapsed, err)
		} else {
			passed++
			fmt.Printf("✅ [%s] PASSED (%dms)\n", name, elapsed)
		}
	}

	// 1. Kernel Lifecycle
	fmt.Println("\n--- Testing Kernel & Session Service ---")
	runTest("kernel.GetStatusReport", func() error {
		rep, err := kernelSvc.GetStatusReport(ctx)
		if err != nil {
			return err
		}
		if !rep.IsConnected {
			return fmt.Errorf("expected is_connected=true")
		}
		data, _ := json.Marshal(rep)
		fmt.Printf("   Kernel Payload: %s\n", string(data))
		return nil
	})

	runTest("kernel.ListSessions", func() error {
		sessions, err := kernelSvc.ListSessions(ctx)
		if err != nil {
			return err
		}
		if len(sessions) == 0 {
			return fmt.Errorf("no sessions found")
		}
		return nil
	})

	runTest("kernel.ListKernels", func() error {
		kernels, err := kernelSvc.ListKernels(ctx)
		if err != nil {
			return err
		}
		if len(kernels) == 0 {
			return fmt.Errorf("no kernels found")
		}
		return nil
	})

	runTest("kernel.GetAvailableAccelerators", func() error {
		report, err := kernelSvc.GetAvailableAccelerators(ctx)
		if err != nil {
			return err
		}
		if len(report.Accelerators) == 0 {
			return fmt.Errorf("no accelerators returned")
		}
		fmt.Printf("   Available accelerators found: %d options\n", len(report.Accelerators))
		return nil
	})

	// 2. Hardware Telemetry
	fmt.Println("\n--- Testing Hardware & Environment Telemetry Service ---")
	runTest("telemetry.GetHardwareTelemetry", func() error {
		telem, err := telemetrySvc.GetHardwareTelemetry(ctx)
		if err != nil {
			return err
		}
		data, _ := json.Marshal(telem)
		fmt.Printf("   Hardware Payload: %s\n", string(data))
		return nil
	})

	runTest("telemetry.GetBuildInfo", func() error {
		info, err := telemetrySvc.GetBuildInfo(ctx)
		if err != nil {
			return err
		}
		fmt.Printf("   Build Tag: %s\n", info.ReleaseTag)
		return nil
	})

	runTest("telemetry.CheckDriveStatus", func() error {
		status, err := telemetrySvc.CheckDriveStatus(ctx)
		if err != nil {
			return err
		}
		data, _ := json.Marshal(status)
		fmt.Printf("   Drive Status Payload: %s\n", string(data))
		return nil
	})

	// 3. Storage & Non-blocking File I/O
	fmt.Println("\n--- Testing Non-blocking File I/O Engine ---")
	runTest("storage.ListDirectory(content)", func() error {
		dir, err := storageSvc.ListDirectory(ctx, "content")
		if err != nil {
			return err
		}
		fmt.Printf("   Directory contains %d entries\n", dir.TotalEntries)
		return nil
	})

	testFilePath := "content/harness_verification.txt"
	testFileContent := "Enterprise GoLab Harness Live Verification\nGenerated by Codex Harness Suite\nTimestamp: " + time.Now().Format(time.RFC3339)

	runTest("storage.WriteFile", func() error {
		res, err := storageSvc.WriteFile(ctx, testFilePath, testFileContent, "text")
		if err != nil {
			return err
		}
		if res.Size <= 0 {
			return fmt.Errorf("written size is 0")
		}
		return nil
	})

	runTest("storage.ReadFile", func() error {
		res, err := storageSvc.ReadFile(ctx, testFilePath, "text")
		if err != nil {
			return err
		}
		if res.Content != testFileContent {
			return fmt.Errorf("content mismatch")
		}
		return nil
	})

	testDir := "content/harness_test_dir"
	runTest("storage.CreateDirectory", func() error {
		return storageSvc.CreateDirectory(ctx, testDir)
	})

	movedPath := testDir + "/moved_verification.txt"
	runTest("storage.MoveFile", func() error {
		return storageSvc.MoveFile(ctx, testFilePath, movedPath)
	})

	runTest("storage.DeleteFile(moved file)", func() error {
		return storageSvc.DeleteFile(ctx, movedPath)
	})

	runTest("storage.DeleteFile(test directory)", func() error {
		return storageSvc.DeleteFile(ctx, testDir)
	})

	runTest("storage.ReadFile(unmounted drive path guardrail)", func() error {
		_, err := storageSvc.ReadFile(ctx, "content/drive/MyDrive/missing_model.bin", "text")
		if err == nil {
			return fmt.Errorf("expected error for unmounted drive path, got nil")
		}
		fmt.Printf("   Anti-hallucination error caught: %v\n", err)
		return nil
	})
	// 4. Notebook DOM Precision Editing
	fmt.Println("\n--- Testing Notebook DOM Cell Editor ---")
	runTest("notebook.GetNotebookOutline", func() error {
		outline, err := notebookSvc.GetNotebookOutline(ctx)
		if err != nil {
			return err
		}
		fmt.Printf("   Notebook has %d cells (%d code, %d markdown)\n", outline.TotalCells, outline.CodeCells, outline.MarkdownCells)
		return nil
	})

	runTest("notebook.GetCells", func() error {
		cells, err := notebookSvc.GetCells(ctx, 0, 10, true)
		if err != nil {
			return err
		}
		if len(cells) == 0 {
			return fmt.Errorf("expected at least 1 cell")
		}
		return nil
	})

	runTest("notebook.GetRunningCells", func() error {
		report, err := notebookSvc.GetRunningCells(ctx, false)
		if err != nil {
			return err
		}
		fmt.Printf("   Running cells check: has_running=%t, total=%d\n", report.HasRunningCells, report.TotalRunning)
		return nil
	})

	// 5. Terminal Service
	fmt.Println("\n--- Testing Linux Terminal Service ---")
	runTest("terminal.ListTerminals", func() error {
		terminals, err := terminalSvc.ListTerminals(ctx)
		if err != nil {
			return err
		}
		fmt.Printf("   Active Linux PTY terminals: %d\n", len(terminals))
		return nil
	})

	// 6. Proxy Service
	fmt.Println("\n--- Testing Reverse Proxy Gateway (/_proxy/<port>/) ---")
	runTest("proxy.ProxyForward(3453, api/contents)", func() error {
		resp, err := proxySvc.ProxyForward(ctx, 3453, "api/contents", "GET", nil, "")
		if err != nil {
			return err
		}
		if !resp.OK {
			return fmt.Errorf("proxy returned status %d", resp.Status)
		}
		return nil
	})

	fmt.Printf("\n=======================================================\n")
	fmt.Printf("TEST SUMMARY: %d/%d PASSED (Success Rate: %.1f%%)\n", passed, total, (float64(passed)/float64(total))*100)
	fmt.Printf("=======================================================\n\n")

	if passed < total {
		os.Exit(1)
	}
}
